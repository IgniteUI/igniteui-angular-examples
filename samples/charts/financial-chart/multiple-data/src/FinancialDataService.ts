import { Injectable } from "@angular/core";

/** One trading day of open, high, low and close prices together with the traded volume. */
export interface StockItem {
    time: Date;
    open: number;
    high: number;
    low: number;
    close: number;
    volume: number;
}

/** A stock's daily history plus the title that the financial chart shows in its legend. */
export type StockSeries = StockItem[] & { title: string };

/** Compact raw row: ISO date (YYYY-MM-DD), open, high, low, close, volume. */
type StockRow = [date: string, open: number, high: number, low: number, close: number, volume: number];

/**
 * Provides real daily stock prices for Microsoft (MSFT) and Alphabet/Google (GOOGL)
 * covering five years, from September 2021 to September 2026 (source: Nasdaq historical quotes).
 * Prices are split-adjusted (GOOGL had a 20-for-1 split in July 2022), so the
 * percent-change comparison drawn by the financial chart stays continuous.
 */
@Injectable({ providedIn: "root" })
export class FinancialDataService {

    /** Both series in the order they should appear in the chart's legend. */
    public getMultiple(): StockSeries[] {
        return [this.getMicrosoft(), this.getGoogle()];
    }

    public getMicrosoft(): StockSeries {
        return toSeries("Microsoft (MSFT)", MICROSOFT_ROWS);
    }

    public getGoogle(): StockSeries {
        return toSeries("Google (GOOGL)", GOOGLE_ROWS);
    }
}

function toSeries(title: string, rows: readonly StockRow[]): StockSeries {
    const series = rows.map(toItem) as StockSeries;
    series.title = title;
    return series;
}

function toItem([date, open, high, low, close, volume]: StockRow): StockItem {
    const [year, month, day] = date.split("-").map(Number);
    // build the date in local time so the calendar day is not shifted by the time zone offset
    return { time: new Date(year, month - 1, day), open, high, low, close, volume };
}

